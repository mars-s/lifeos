"""Export the existing Python widget contracts for the cloud connector.

Run with uv run python scripts/export-ui-contracts.py after changing UI models.
The output contains schemas only, never runtime captures or task content.
"""

import argparse
import asyncio
import json
from pathlib import Path

from fastmcp import Client

from lifeos.cloud_bridge import LOCAL_TOOLS
from lifeos.server import create_mcp
from lifeos.ui import BrainDumpCanvasOutput, DayPlanWidgetOutput, WeekPlanWidgetOutput

target = Path(__file__).resolve().parents[1] / "cloud-mirror/cloudflare/ui-contracts.json"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true", help="Fail if checked-in contracts are stale")
check = parser.parse_args().check


def emit(path: Path, content: str) -> None:
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise RuntimeError(f"stale schema contract: {path.name}")
    else:
        path.write_text(content, encoding="utf-8")


contracts = {
    model.__name__: model.model_json_schema()
    for model in (DayPlanWidgetOutput, WeekPlanWidgetOutput, BrainDumpCanvasOutput)
}
emit(target, json.dumps(contracts, ensure_ascii=False, indent=2) + "\n")


async def export_tools() -> None:
    # Registration closes over the service, but schema export invokes no tool.
    server = create_mcp(None)  # type: ignore[arg-type]
    async with Client(server) as client:
        tools = await client.list_tools()
    exported = [tool.model_dump(mode="json", exclude_none=True) for tool in tools if tool.name in LOCAL_TOOLS]
    if {tool["name"] for tool in exported} != LOCAL_TOOLS:
        raise RuntimeError("bridge tool allowlist differs from registered tools")
    emit(target.with_name("local-tool-contracts.json"), json.dumps(exported, ensure_ascii=False, indent=2) + "\n")
    renderers = {
        tool.name: tool.inputSchema for tool in tools
        if tool.name in {"render_day_plan", "render_week_plan"}
    }
    emit(target.with_name("ui-tool-contracts.json"), json.dumps(renderers, ensure_ascii=False, indent=2) + "\n")
    swift = target.parents[2] / "mac-sync/Sources/SyncCore/LocalToolContract.swift"
    names = ",\n".join(f'        "{name}"' for name in sorted(LOCAL_TOOLS))
    emit(swift,
        "// Generated by scripts/export-ui-contracts.py. Schema-only, no private data.\n"
        "public enum LocalToolContract {\n    public static let names: Set<String> = [\n"
        + names + "\n    ]\n}\n"
    )


asyncio.run(export_tools())
